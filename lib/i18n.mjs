/** 取一条本地化文案，{name} 占位按 vars 替换 */
export function tr(locale, key, vars = {}) {
  const table = TEXT[normalizeLocale(locale)];
  const template = table[key] !== undefined ? table[key] : (TEXT.zh[key] !== undefined ? TEXT.zh[key] : key);
  return String(template).replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? String(vars[name]) : match));
}

/** 带文案 key 的错误：HTTP 层按请求方的语言翻译 */
export class CourtError extends Error {
  constructor(key, vars = {}) {
    super(tr('zh', key, vars));
    this.key = key;
    this.vars = vars;
  }
}

export const fail = (key, vars) => { throw new CourtError(key, vars); };

export function errorText(error, locale) {
  if (error && error.key) return tr(locale, error.key, error.vars);
  return String(error && error.message ? error.message : error);
}

