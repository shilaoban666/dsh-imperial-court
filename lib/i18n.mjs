export function roleTitle(locale, id) {
  const table = ROLE_TEXT[normalizeLocale(locale)];
  return (table[id] && table[id].title) || String(id || '');
}

/** 职掌：用户改过的原样用；还是某种语言的默认值时，换成当前语言的默认值 */
export function roleDuty(locale, id, duty) {
  const own = String(duty || '').trim();
  const zh = ROLE_TEXT.zh[id] && ROLE_TEXT.zh[id].duty;
  const en = ROLE_TEXT.en[id] && ROLE_TEXT.en[id].duty;
  if (!own || own === zh || own === en) return (ROLE_TEXT[normalizeLocale(locale)][id] || {}).duty || own;
  return own;
}

